#!/usr/bin/env python3
"""Pick the Material Bibata cursor theme closest to an Omarchy theme accent.

colors.tsv holds one row per family and mode (family, mode, primary hex) and is
generated by install.sh from upstream themes.json. Matching is hue-dominant in
LCh and restricted to the mode the Omarchy theme declares, so dark themes only
ever match dark cursor art and light themes only light art.
"""

from __future__ import annotations

import argparse
import math
import os
import re
import sys

HEX = re.compile(r"^#?[0-9A-Fa-f]{6}$")


def rgb(value: str) -> tuple[float, float, float]:
    digits = value.strip().lstrip("#")
    return tuple(int(digits[index : index + 2], 16) / 255.0 for index in (0, 2, 4))


def linear(channel: float) -> float:
    return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4


def lab(value: str) -> tuple[float, float, float]:
    red, green, blue = (linear(channel) for channel in rgb(value))
    x = red * 0.4124564 + green * 0.3575761 + blue * 0.1804375
    y = red * 0.2126729 + green * 0.7151522 + blue * 0.0721750
    z = red * 0.0193339 + green * 0.1191920 + blue * 0.9503041

    def curve(component: float) -> float:
        return component ** (1 / 3) if component > 216 / 24389 else (24389 / 27 * component + 16) / 116

    fx, fy, fz = curve(x / 0.95047), curve(y), curve(z / 1.08883)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def lch(value: str) -> tuple[float, float, float]:
    lightness, a, b = lab(value)
    return lightness, math.hypot(a, b), math.degrees(math.atan2(b, a)) % 360


def closeness(accent: tuple[float, float, float], candidate: tuple[float, float, float]) -> float:
    """Lower is closer.

    Hue is weighted by the accent's own chroma: Omarchy's accents are far more
    saturated than Bibata's pastel primaries, so a fixed hue weight would drag an
    orange accent onto beige and a cream accent onto olive. Near-grey accents
    (chroma ~0) therefore match on lightness and chroma instead of a meaningless
    hue, which lands them on the neutral families where they belong.
    """
    accent_l, accent_c, accent_h = accent
    cand_l, cand_c, cand_h = candidate
    gap = abs(accent_h - cand_h)
    return (
        2.0 * min(accent_c, 60.0) / 60.0 * min(gap, 360.0 - gap)
        + 0.5 * abs(accent_l - cand_l)
        + 0.6 * abs(accent_c - cand_c)
    )


def main() -> int:
    default_table = os.path.join(os.path.dirname(os.path.abspath(__file__)), "colors.tsv")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", required=True, choices=("dark", "light"))
    parser.add_argument("--accent", required=True)
    parser.add_argument("--table", default=default_table)
    args = parser.parse_args()

    if not HEX.match(args.accent):
        print(f"invalid accent: {args.accent!r}", file=sys.stderr)
        return 1

    target = lch(args.accent)
    best: tuple[float, str] | None = None
    with open(args.table, encoding="utf-8") as table:
        for line in table:
            family, mode, value = line.rstrip("\n").split("\t")
            if mode != args.mode:
                continue
            candidate = (closeness(target, lch(value)), family)
            if best is None or candidate < best:
                best = candidate

    if best is None:
        print("colour table has no entry for this mode", file=sys.stderr)
        return 1

    suffix = "-Light" if args.mode == "light" else ""
    print(f"Bibata-Material-{best[1]}{suffix}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
